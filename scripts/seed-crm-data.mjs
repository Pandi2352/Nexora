async function seed() {
  console.log(`Connecting to MongoDB at ${MONGODB_URI}...`)
  await mongoose.connect(MONGODB_URI)
  const db = mongoose.connection.db

  const orgs = await db.collection('organizations').find({}).toArray()
  if (orgs.length === 0) {
    console.error('No organizations found in database. Please log in or create an organization first.')
    await mongoose.disconnect()
    process.exit(1)
  }

  const user = await db.collection('users').findOne({})
  const userId = user ? user._id : randomUUID()

  console.log(`Found ${orgs.length} organization(s): ${orgs.map((o) => o.slug).join(', ')}`)

  for (const org of orgs) {
    const orgId = org._id
    console.log(`\n--- Seeding for Organization: "${org.name}" (${org.slug}, ID: ${orgId}) ---`)

    // 1. Companies
    await db.collection('companies').deleteMany({ organizationId: orgId })
    const companiesToInsert = COMPANIES_DATA.map((c, idx) => ({
      _id: randomUUID(),
      organizationId: orgId,
      ownerId: userId,
      ...c,
      createdAt: new Date(Date.now() - (idx + 1) * 2 * 86400000),
      updatedAt: new Date(Date.now() - idx * 86400000),
    }))
    await db.collection('companies').insertMany(companiesToInsert)
    console.log(`✓ Inserted ${companiesToInsert.length} companies into MongoDB`)

    // 2. Contacts
    await db.collection('contacts').deleteMany({ organizationId: orgId })
    const contactsToInsert = CONTACTS_DATA.map((ct, idx) => {
      const company = companiesToInsert[idx % companiesToInsert.length]
      return {
        _id: randomUUID(),
        organizationId: orgId,
        companyId: company._id,
        ...ct,
        createdAt: new Date(Date.now() - (idx + 1) * 2 * 86400000),
        updatedAt: new Date(Date.now() - idx * 86400000),
      }
    })
    await db.collection('contacts').insertMany(contactsToInsert)
    console.log(`✓ Inserted ${contactsToInsert.length} contacts into MongoDB`)

    // 3. Opportunities (Deals)
    await db.collection('opportunities').deleteMany({ organizationId: orgId })
    const oppsToInsert = OPPORTUNITIES_DATA.map((op, idx) => {
      const company = companiesToInsert[idx % companiesToInsert.length]
      return {
        _id: randomUUID(),
        organizationId: orgId,
        companyId: company._id,
        companyName: company.name,
        ownerId: userId,
        expectedCloseDate: new Date(Date.now() + (idx + 7) * 4 * 86400000),
        ...op,
        createdAt: new Date(Date.now() - (idx + 1) * 2 * 86400000),
        updatedAt: new Date(Date.now() - idx * 86400000),
      }
    })
    await db.collection('opportunities').insertMany(oppsToInsert)
    console.log(`✓ Inserted ${oppsToInsert.length} opportunities (deals) into MongoDB`)

    // 4. Sales Activities
    await db.collection('sales_activities').deleteMany({ organizationId: orgId })
    const activitiesToInsert = ACTIVITIES_DATA.map((act, idx) => {
      const company = companiesToInsert[idx % companiesToInsert.length]
      const actDate = new Date(Date.now() - act.daysAgo * 86400000)
      return {
        _id: randomUUID(),
        organizationId: orgId,
        performedById: userId,
        companyId: company._id,
        type: act.type,
        title: act.title,
        description: act.description,
        status: act.status,
        outcome: act.outcome,
        proposalValue: act.proposalValue,
        completedAt: actDate,
        createdAt: actDate,
        updatedAt: actDate,
      }
    })
    await db.collection('sales_activities').insertMany(activitiesToInsert)
    console.log(`✓ Inserted ${activitiesToInsert.length} sales activities into MongoDB`)

    // 5. Business Units
    await db.collection('business_units').deleteMany({ organizationId: orgId })
    const busToInsert = BUSINESS_UNITS_DATA.map((b, idx) => ({
      _id: randomUUID(),
      organizationId: orgId,
      createdById: userId,
      ...b,
      createdAt: new Date(Date.now() - (idx + 1) * 3 * 86400000),
      updatedAt: new Date(Date.now() - idx * 86400000),
    }))
    await db.collection('business_units').insertMany(busToInsert)
    console.log(`✓ Inserted ${busToInsert.length} business units into MongoDB`)

    // 6. Leads
    await db.collection('leads').deleteMany({ organizationId: orgId })
    const leadsToInsert = LEADS_DATA.map((l, idx) => ({
      _id: randomUUID(),
      organizationId: orgId,
      leadOwnerId: userId,
      ...l,
      createdAt: new Date(Date.now() - (idx + 1) * 2 * 86400000),
      updatedAt: new Date(Date.now() - idx * 86400000),
    }))
    await db.collection('leads').insertMany(leadsToInsert)
    console.log(`✓ Inserted ${leadsToInsert.length} leads into MongoDB`)
  }

  console.log('\nAll CRM collections (Companies, Contacts, Deals, Activities, BU, Leads) successfully seeded in MongoDB!')
  await mongoose.disconnect()
}

seed().catch((err) => {
  console.error('Error during seeding:', err)
  process.exit(1)
})
